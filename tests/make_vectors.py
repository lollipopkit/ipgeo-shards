#!/usr/bin/env python3
"""Regenerates the shared test vectors.

    python3 tests/make_vectors.py

The vectors are the only thing making this repository's writer and ServerBox's
reader agree. Each is a pair: a small binary built here, and a JSON file
listing what looking things up in it must answer. **Neither side reimplements
the other's half to check them** — the reader loads the binary and compares
against the JSON, so a disagreement about the format shows up as a wrong
answer rather than as two encoders that happen to differ.

The expected coordinates are the *decoded* values, quantisation already
applied, so both sides compare exactly rather than within a tolerance.

Copy the whole directory into the app at `test/fixtures/geo/` after running
this. Do not regenerate a vector to make a failing test pass.
"""

from __future__ import annotations

import ipaddress
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

import formats  # noqa: E402
from formats import CountryRange  # noqa: E402

HERE = Path(__file__).resolve().parent / "vectors"

#: Deliberately chosen so every branch of a reader is reachable:
#: the first record is not at address zero, one country is absent from the
#: table, there is a gap in the middle, and there is a range past the last one.
COUNTRIES = {
    "AU": (-35.2809, 149.1300),
    "CN": (39.9042, 116.4074),
    "US": (38.9072, -77.0369),
}

IP4 = [
    ("1.0.0.0", "CN"),
    ("8.0.0.0", "US"),
    ("9.0.0.0", None),  # a gap: allocated to nothing
    ("101.0.0.0", "AU"),
    ("200.0.0.0", "US"),  # above 2^31, where a signed read would go wrong
]

IP6 = [
    ("2001:200::", "CN"),
    ("2600::", "US"),
    ("2700::", None),
    ("f000::", "AU"),  # top half of the space
]

LOOKUPS = [
    # IPv4
    ("1.2.3.4", "CN"),
    ("8.0.0.0", "US"),  # the first address of a block is inside it
    ("8.255.255.255", "US"),  # and the last
    ("9.9.9.9", None),  # the gap
    ("0.255.255.255", None),  # below the first record
    ("200.1.2.3", "US"),
    ("255.255.255.255", "US"),  # past the last record, which has no end
    # IPv6
    ("2001:200:0:1::9", "CN"),
    ("2600:1:2::5", "US"),
    ("2600:1:2:ffff::9", "US"),  # same /48 as the line above
    ("2700::1", None),
    ("2001:100::1", None),  # below the first record
    ("f000::1", "AU"),
]


def decoded(code: str) -> dict[str, float]:
    lat, lon = formats.quantise(*COUNTRIES[code])
    return {"lat": lat / formats.QUANTUM * 90, "lon": lon / formats.QUANTUM * 180}


def main() -> None:
    shift = 128 - formats.IP6_KEY_BITS
    blob = formats.build_country_db(
        COUNTRIES,
        [CountryRange(int(ipaddress.IPv4Address(ip)), cc) for ip, cc in IP4],
        [
            CountryRange(int(ipaddress.IPv6Address(ip)) >> shift, cc)
            for ip, cc in IP6
        ],
    )

    HERE.mkdir(parents=True, exist_ok=True)
    (HERE / "country_v1.bin").write_bytes(blob)

    spec = {
        "format": formats.COUNTRY_FORMAT,
        "note": (
            "Generated by tests/make_vectors.py in lollipopkit/ipgeo-shards. "
            "The reader under test must load country_v1.bin and answer exactly "
            "this for each address. A null expectation means no coordinate, "
            "which is not the same as an error."
        ),
        "ip6KeyBits": formats.IP6_KEY_BITS,
        "countries": {code: decoded(code) for code in sorted(COUNTRIES)},
        "lookups": [
            {"ip": ip, "expect": decoded(cc) if cc else None, "country": cc}
            for ip, cc in LOOKUPS
        ],
    }
    (HERE / "country_v1.json").write_text(
        json.dumps(spec, indent=2, sort_keys=True) + "\n"
    )
    print(f"wrote {HERE}/country_v1.bin ({len(blob)} bytes) and country_v1.json")


if __name__ == "__main__":
    main()
